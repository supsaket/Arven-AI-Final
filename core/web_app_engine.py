"""Feature 118 — Autonomous Web / App / Game Creation & QA.

A real, bounded build and QA loop:

   REQUIREMENTS -> PLAN -> IMPLEMENT -> BUILD -> RUN -> INSPECT -> TEST ->
   DETECT_FAILURE -> FIX -> REBUILD -> RETEST -> FINAL_VERIFY

Honesty contract:
* every generated project is REAL runnable code; ``BUILD`` compiles it with
  ``py_compile``, ``RUN`` launches it as a real subprocess (bounded) and only
  reports success when the process genuinely starts, ``TEST`` executes pytest;
* a failing build is never reported as success. ``FIX`` appends a deterministic
  review hint and loops — it never fabricates a repair;
* final ``FINAL_VERIFY`` is a fresh build+run+test pass, and its verdict is the
  only place the loop claims completion;
* generated artifacts are stored in a caller-provided workspace directory
  (tests use tmp paths) with metadata sidecars.

The loop is deterministic and offline (stdlib only).
"""

