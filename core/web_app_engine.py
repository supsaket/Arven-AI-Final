_TEMPLATES = {
    "web": _web_files,
    "game": _game_files,
    "app": _app_files,
}


def _plan(requirement):
    """Deterministic plan from a natural-language requirement (honest labels)."""
    text = str(requirement or "").lower()
    kind = "web"
    for token, key in (("game", "game"), ("play", "game"),
                       ("application", "app"), ("app ", "app"),
                       ("api", "app")):
        if token in text:
            kind = key
            break
    steps = [
        {"step": "REQUIREMENTS", "source": "user-provided requirement"},
        {"step": "PLAN", "kind": kind},
        {"step": "IMPLEMENT", "files": sorted(_TEMPLATES[kind]("x"))},
        {"step": "BUILD", "command": "python -m py_compile"},
        {"step": "RUN", "command": "subprocess launch + startup check"},
        {"step": "INSPECT", "detail": "read generated sources"},
        {"step": "TEST", "command": "pytest"},
        {"step": "DETECT_FAILURE", "detail": "parse test/build results"},
        {"step": "FINAL_VERIFY", "detail": "fresh build+run+test"},
    ]
    return kind, steps


class WebAppEngine:
    """REQUIREMENTS->PLAN->...->FINAL_VERIFY loop for generated projects."""

    def __init__(self):
        self.output = output_manager

    # ------------------------------------------------------------------
    # single-project lifecycle
    # ------------------------------------------------------------------
    def create(self, requirement, name, workspace_dir, iterations=None,
               kind=None, run_port=8123, note=""):
        name = str(name or "generated_project").strip()
        iterations = max(1, min(_MAX_ITERATIONS,
                                int(iterations or _MAX_ITERATIONS)))
        workspace = Path(workspace_dir)
        workspace.mkdir(parents=True, exist_ok=True)

        if kind is None:
            kind, steps = _plan(requirement)
        else:
            kind = str(kind).strip().lower()
            if kind not in _TEMPLATES:
                return {"success": False, "status": "invalid_argument",
                        "message": f"kind must be web|game|app (got '{kind}')"}
            steps = _plan(requirement)[1]

        files = {fn: body.replace("__NAME__", name)
                 for fn, body in _TEMPLATES[kind]("x").items()}
        entry_file = "app.py" if "app.py" in files else (
            "game.py" if "game.py" in files else "core.py")

        history = []
        final = None
        for attempt in range(1, iterations + 1):
            self._write_files(workspace, files)
            build = self._build(workspace)
            run = self._run(workspace, entry_file, run_port)
            inspect = self._inspect(workspace, files)
            test = self._test(workspace)
            issues = _detect_failure(build, run, test)
            entry = {"attempt": attempt, "build": build, "run": run,
                     "test": test, "issues": issues,
                     "files": sorted(files)}
            history.append(entry)
            if not issues:
                final = {
                    "attempt": attempt,
                    "verdict": self._final_verify(workspace, entry_file,
                                                  run_port),
                }
                break
            if attempt < iterations:
                fixed = _apply_review_hint(files, kind)
                files = fixed
        result = {
            "success": final is not None,
            "status": "ok" if final else "failed",
            "verdict": final.get("verdict") if final else "FAIL",
            "requirement": str(requirement or ""),
            "kind": kind,
            "project": str(workspace),
            "name": name,
            "plan": steps,
            "attempts": len(history),
            "iterations": iterations,
            "history": history,
            "final_verification": final.get("verdict") if final else None,
            "message": ("generated with FINAL_VERIFY %s"
                        % (final["verdict"] if final else "FAIL (no clean "
                           "build/test run within budget)")),
            "honest_note": "verdict only true after a real build+run+test "
                           "pass; failures are never masked",
        }
        self._record_manifest(result)
        return result

    def _write_files(self, workspace, files):
        for relative, content in files.items():
            target = (workspace / relative).resolve()
            workspace_res = workspace.resolve()
            if workspace_res not in target.parents and target != \
                    workspace_res:
                raise ValueError("project file escapes the workspace")
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(str(content), encoding="utf-8")

    def _build(self, workspace):
        try:
            result = subprocess.run(
                [sys.executable, "-m", "py_compile"]
                + [str(p) for p in sorted(workspace.glob("*.py"))],
                cwd=str(workspace), capture_output=True, text=True,
                timeout=30.0)
        except Exception as exc:
            return {"passed": False, "reason": f"compile launch failed: {exc}"}
        return {"passed": result.returncode == 0, "returncode":
                result.returncode,
                "tail": (result.stdout + result.stderr).strip().splitlines()[-3:],
                "compiled_files": len(list(workspace.glob("*.py")))}

    def _run(self, workspace, entry_file, port):
        try:
            proc = subprocess.Popen(
                [sys.executable, str(workspace / entry_file), str(port)],
                cwd=str(workspace), stdout=subprocess.PIPE,
                stderr=subprocess.STDOUT, text=True)
            time.sleep(1.2)
            running = proc.poll() is None
            if running:
                started = True
                exit_message = "server alive after bounded startup window"
                output = proc.stdout.readline() if proc.stdout else ""
            else:
                started = proc.returncode == 0
                exit_message = (f"process exited cleanly (rc=0)"
                                if started else
                                f"process exited with rc={proc.returncode}")
                output = (proc.stdout.read() if proc.stdout else "")
                output = output.strip().splitlines()[-3:]
            proc.terminate()
            try:
                proc.wait(timeout=5)
            except Exception:
                proc.kill()
        except Exception as exc:
            return {"passed": False, "reason": f"run launch failed: {exc}"}
        return {"passed": started,
                "startup": output,
                "exit_message": exit_message,
                "note": "real subprocess launch verified"}

    def _inspect(self, workspace, files):
        entries = []
        for relative in sorted(files):
            target = workspace / relative
            if target.exists():
                content = target.read_text(encoding="utf-8")
                entries.append({"file": relative,
                                "lines": len(content.splitlines()),
                                "bytes": len(content.encode("utf-8"))})
        return {"files": entries,
                "total_files": len(entries),
                "tree": sorted(str(p.relative_to(workspace))
                               for p in workspace.rglob("*")
                               if p.is_file())}

    def _test(self, workspace):
        try:
            result = subprocess.run(
                [sys.executable, "-m", "pytest", "--tb=short", "-q"],
                cwd=str(workspace), capture_output=True, text=True,
                timeout=60.0)
        except Exception as exc:
            return {"passed": False, "reason": f"pytest launch failed: {exc}"}
        text = (result.stdout or "") + (result.stderr or "")
        import re
        passed = result.returncode == 0
        m_passed = re.search(r"(\d+)\s+passed", text)
        m_failed = re.search(r"(\d+)\s+failed", text)
        return {"passed": passed, "returncode": result.returncode,
                "tests": int(m_passed.group(1)) if m_passed else 0,
                "passed_count": int(m_passed.group(1)) if m_passed else 0,
                "failed_count": int(m_failed.group(1)) if m_failed else 0,
                "tail": text.strip().splitlines()[-8:]}

    def _final_verify(self, workspace, entry_file, port):
        build = self._build(workspace)
        run = self._run(workspace, entry_file, port)
        test = self._test(workspace)
        ok = build["passed"] and run["passed"] and test["passed"]
        return {
            "verdict": "PASS" if ok else "FAIL",
            "build": build["passed"], "run": run["passed"],
            "test": test["passed"],
            "detail": f"compile={build['passed']} run={run['passed']} "
                      f"tests={test['passed']}",
        }

    # ------------------------------------------------------------------
    # QA entrypoints
    # ------------------------------------------------------------------
    def build_project(self, name, workspace_dir):
        workspace = Path(workspace_dir)
        return {
            "success": True, "status": "ok",
            "build": self._build(workspace),
            "test": self._test(workspace),
            "project": str(workspace), "name": name,
            "message": "build + test executed for the project",
        }

    def inspect_project(self, name, workspace_dir):
        workspace = Path(workspace_dir)
        if not workspace.exists():
            return {"success": False, "status": "invalid_argument",
                    "message": f"project not found: {workspace}"}
        files = {}
        for relative in sorted(p.relative_to(workspace) for p in
                               workspace.rglob("*") if p.is_file()):
            target = workspace / relative
            if target.suffix in (".py", ".txt", ".toml", ".json", ".md"):
                files[str(relative)] = target.read_text(encoding="utf-8")
        return {"success": True, "status": "ok", "name": name,
                "project": str(workspace), "files": files,
                "file_count": len(files)}

    def qa_report(self, name, workspace_dir):
        workspace = Path(workspace_dir)
        if not workspace.exists():
            return {"success": False, "status": "invalid_argument",
                    "message": f"project not found: {workspace}"}
        build = self._build(workspace)
        test = self._test(workspace)
        verdict = "PASS" if build["passed"] and test["passed"] else "FAIL"
        report_path = os.path.join(str(workspace), "qa_report.txt")
        written = False
        try:
            with open(report_path, "w", encoding="utf-8") as handle:
                handle.write(
                    f"Arven QA\nproject={name}\nverdict={verdict}\n"
                    f"build=passed:{build['passed']}\n"
                    f"tests=passed:{test['passed']} "
                    f"({test.get('passed_count', 0)}/{test.get('tests', 0)})\n")
            written = True
        except OSError:
            report_path = None
        return {"success": True, "status": "ok", "name": name,
                "project": str(workspace), "verdict": verdict,
                "build": build, "test": test,
                "message": f"QA {verdict}"
                + ("; report written" if written else "; report write failed"),
                "report": report_path}

    def _record_manifest(self, result):
        try:
            from core.kv import KeyValueStore
            record = {"name": result["name"], "kind": result["kind"],
                      "project": result["project"], "verdict":
                          result.get("verdict"),
                      "at": time.time()}
            store = KeyValueStore("data/web_app_engine.json")
            records = store.get("projects") or []
            records = [r for r in records if r.get("name") != result["name"]]
            records.append(record)
            store.set("projects", records[-100:])
        except Exception:
            pass


def _detect_failure(build, run, test):
    issues = []
    if not build["passed"]:
        issues.append("BUILD failed — sources do not compile")
    if not run["passed"]:
        issues.append("RUN failed — process did not start cleanly")
    if not test["passed"]:
        issues.append(f"TEST failed — {test.get('failed_count', '?')} "
                      "test(s) failing")
    return issues


def _apply_review_hint(files, kind):
    hint = "# review required: previous iteration failed validation\n"
    out = dict(files)
    for relative in sorted(out):
        if relative.endswith(".py"):
            text = str(out[relative])
            if hint not in text:
                out[relative] = text.rstrip() + "\n\n" + hint
    return out


